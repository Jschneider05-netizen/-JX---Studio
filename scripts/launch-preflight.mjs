import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
const root = process.cwd();
const errors=[];const passes=[];
const read = (file)=>fs.readFileSync(path.join(root,file),'utf8');
const check=(name,test)=>{if(test)passes.push(name);else errors.push(name);};
const required=['app/page.tsx','app/[studioView]/page.tsx','app/leistungen/[slug]/page.tsx','app/projekte/page.tsx','app/projekte/praxis-am-park/page.tsx','app/studio/page.tsx','app/impressum/page.tsx','app/datenschutz/page.tsx','app/not-found.tsx','app/robots.ts','app/sitemap.ts'];
for(const file of required)check(`route exists ${file}`,fs.existsSync(path.join(root,file)));
const home=read('components/jx-studio.tsx');
const contact=read('app/api/contact/route.ts');
const footer=home.slice(home.indexOf('function Footer('));
check('home has 6 service segments', (home.match(/\["0[1-6]","/g)||[]).length>=6);
check('home contains six-stage workflow', home.includes('Weiterentwicklung') && home.includes('Idee und Erstgespräch'));
check('customer CTA leads to contact', home.includes('Projekt unverbindlich anfragen'));
check('public assistant is not rendered', !home.includes('{view !== "builder" && <JXAssistant'));
check('legal links are real',footer.includes('href="/impressum"')&&footer.includes('href="/datenschutz"'));
check('old address excluded from public', ![home,read('app/impressum/page.tsx'),read('app/datenschutz/page.tsx')].some(x=>x.includes('Albert-Schweitzer-Straße 7')));
check('correct business address',read('app/impressum/page.tsx').includes('Albert-Schweitzer-Straße 6'));
check('site has verified email',footer.includes('kontakt@jx-studio.de') && read('app/datenschutz/page.tsx').includes('kontakt@jx-studio.de'));
check('contact has safe failure status',contact.includes('status: 503') && contact.includes('status: 400'));
check('contact has idempotency',contact.includes('onConflictDoNothing') && contact.includes('requestId'));
check('contact has honeypot',contact.includes('body.website'));
check('contact has origin check',contact.includes('Unerlaubter Ursprung'));
check('contact requires actual persistence or email',contact.includes('if (!savedToDatabase && !emailSent)'));
check('unreleased pages gated',read('app/[studioView]/page.tsx').includes('ENABLE_LEGACY_STUDIO'));
check('assistant API gated',read('app/api/assistant/route.ts').includes('ENABLE_PUBLIC_ASSISTANT'));
check('seo noindex non-production',read('app/robots.ts').includes('disallow:"/"'));
check('sitemap includes primary routes',read('app/sitemap.ts').includes('"/impressum"')&&read('app/sitemap.ts').includes('servicePages.map'));
check('database schema retained',fs.existsSync(path.join(root,'drizzle-pg/0007_jx_studio_order_integrity.sql')));
check('reduced motion styled',read('app/launch.css').includes('prefers-reduced-motion'));
console.log(`Launch preflight: ${passes.length} passed, ${errors.length} failed`);
for(const item of passes)console.log(`  PASS ${item}`);
for(const item of errors)console.error(`  FAIL ${item}`);
if(errors.length)process.exit(1);
